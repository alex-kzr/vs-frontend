import {test,expect} from '@playwright/test';
test.beforeEach(async({baseURL})=>{const url=new URL(baseURL!);if(url.hostname!=='127.0.0.1'||url.port==='48173')throw new Error('Synthetic UI checks require an isolated server.');});
test('profile instructions preserve pay details and unrelated criteria through edit and reload',async({page,request})=>{
 const name='Synthetic instructions '+crypto.randomUUID();
 const instructions='Synthetic: 3 500 USD/month net.\nConfirm country and schedule; do not invent a salary floor.';
 await page.goto('/search-configurations/new');
 await page.getByLabel('Название профиля').fill(name);
 await page.getByLabel('Инструкции и ограничения поиска').fill(instructions);
 await page.getByLabel('Запросы в браузере (по одному на строку)').fill('Rust');
 await page.getByRole('button',{name:'Сохранить запись',exact:true}).click();
 await page.waitForURL(/\/search-configurations\/[a-f0-9-]+$/);
 const id=page.url().split('/').at(-1)!;
 await expect(page.getByText(instructions,{exact:true})).toBeVisible();
 await page.reload();await expect(page.getByText(instructions,{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Редактировать',exact:true}).click();
 await expect(page.getByLabel('Инструкции и ограничения поиска')).toHaveValue(instructions);
 await page.getByLabel('Запросы в браузере (по одному на строку)').fill('Rust\nAPIs');
 await page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
 await expect(page.getByRole('link',{name:'APIs',exact:true})).toBeVisible();
 let stored=(await (await request.get('/api/v1/search-configurations/'+id)).json()).data;
 expect(stored.criteria.instructions).toBe(instructions);expect(stored.criteria.queries).toEqual(['Rust','APIs']);
 await page.getByRole('link',{name:'Редактировать',exact:true}).click();
 await page.getByLabel('Инструкции и ограничения поиска').fill('');
 await page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
 await expect(page.getByRole('link',{name:'Редактировать',exact:true})).toBeVisible();
 stored=(await (await request.get('/api/v1/search-configurations/'+id)).json()).data;
 expect(stored.criteria.instructions).toBeNull();expect(stored.criteria.queries).toEqual(['Rust','APIs']);
});
